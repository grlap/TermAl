// Owns recursive workspace split-tree pruning, pane removal/insertion, and ratios.
// Deliberately does not own pane/tab state, routing, or workspace reducers.
// Split out of `workspace.ts`.

import type { WorkspaceNode } from "./workspace-types";

const DEFAULT_ADJACENT_PANE_SPLIT_RATIO = 0.5;

export function pruneWorkspaceNode(
  node: WorkspaceNode | null,
  availablePaneIds: Set<string>,
): WorkspaceNode | null {
  if (!node) {
    return null;
  }

  if (node.type === "pane") {
    return availablePaneIds.has(node.paneId) ? node : null;
  }

  const first = pruneWorkspaceNode(node.first, availablePaneIds);
  const second = pruneWorkspaceNode(node.second, availablePaneIds);
  if (!first && !second) {
    return null;
  }
  if (!first) {
    return second;
  }
  if (!second) {
    return first;
  }

  return {
    ...node,
    first,
    second,
  };
}

export function removePaneFromTree(
  node: WorkspaceNode | null,
  paneId: string,
): WorkspaceNode | null {
  if (!node) {
    return null;
  }

  if (node.type === "pane") {
    return node.paneId === paneId ? null : node;
  }

  const first = removePaneFromTree(node.first, paneId);
  const second = removePaneFromTree(node.second, paneId);
  if (!first && !second) {
    return null;
  }
  if (!first) {
    return second;
  }
  if (!second) {
    return first;
  }

  return {
    ...node,
    first,
    second,
  };
}

export function insertPaneAdjacent(
  node: WorkspaceNode,
  paneId: string,
  direction: "row" | "column",
  newPaneId: string,
  placeBefore: boolean,
): WorkspaceNode {
  if (node.type === "pane") {
    if (node.paneId !== paneId) {
      return node;
    }

    const insertedPane: WorkspaceNode = {
      type: "pane",
      paneId: newPaneId,
    };

    return {
      id: crypto.randomUUID(),
      type: "split",
      direction,
      ratio: DEFAULT_ADJACENT_PANE_SPLIT_RATIO,
      first: placeBefore ? insertedPane : node,
      second: placeBefore ? node : insertedPane,
    };
  }

  return {
    ...node,
    first: insertPaneAdjacent(
      node.first,
      paneId,
      direction,
      newPaneId,
      placeBefore,
    ),
    second: insertPaneAdjacent(
      node.second,
      paneId,
      direction,
      newPaneId,
      placeBefore,
    ),
  };
}

export function updateSplitRatioInNode(
  node: WorkspaceNode,
  splitId: string,
  ratio: number,
): WorkspaceNode {
  if (node.type === "pane") {
    return node;
  }

  if (node.id === splitId) {
    return {
      ...node,
      ratio,
    };
  }

  return {
    ...node,
    first: updateSplitRatioInNode(node.first, splitId, ratio),
    second: updateSplitRatioInNode(node.second, splitId, ratio),
  };
}
